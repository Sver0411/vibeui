/**
 * One-off performance refactor: split the handwritten `ai` block out of every
 * registry metadata.ts so the client bundle can import slim metas without the
 * heavy prompts/knobs/pitfalls prose.
 *
 * - For each metadata.ts with an inline `  ai: {` block:
 *     1. evaluate the TS module (typescript transpile) to read the object,
 *     2. write a sibling ai.ts exporting the layer as a typed const,
 *     3. remove the block from metadata.ts (text surgery keeps comments).
 * - Regenerates src/registry/ai-data.ts (server-only full layers).
 * - Regenerates src/registry/ai-terms.ts (client-safe terms+effectTags only).
 */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import ts from "typescript";

const ROOT = "src/registry";

function walk(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

const files = walk(ROOT).filter((f) => f.endsWith("metadata.ts"));
const aiImports = [];
const terms = {};
let slimCount = 0;
let aiCount = 0;

for (const file of files) {
  const src = fs.readFileSync(file, "utf8");
  const js = ts.transpileModule(src, {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2019 },
  }).outputText;
  const sandbox = { exports: {}, require: (id) => { throw new Error("unexpected require: " + id); } };
  sandbox.module = sandbox;
  vm.runInNewContext(js, sandbox);
  const meta = sandbox.exports.meta;
  if (!meta || !meta.slug) {
    console.error("NO META EXPORT:", file);
    process.exit(1);
  }

  const lines = src.split("\n");
  const start = lines.findIndex((l) => l === "  ai: {");
  if (start >= 0) {
    let end = -1;
    for (let i = start + 1; i < lines.length; i++) {
      if (lines[i] === "  },") { end = i; break; }
    }
    if (end < 0) { console.error("AI BLOCK END NOT FOUND:", file); process.exit(1); }
    const aiObj = meta.ai;
    if (!aiObj || !aiObj.terms) { console.error("EVAL MISSING AI:", file); process.exit(1); }

    const aiDir = path.dirname(file);
    const aiSrc =
      'import type { ResourceAILayer } from "@/types/resource";\n\n' +
      "/** Handwritten AI layer — split from metadata.ts, imported only by the server registry barrel. */\n" +
      "export const ai: ResourceAILayer = " + JSON.stringify(aiObj, null, 2) + ";\n";
    fs.writeFileSync(path.join(aiDir, "ai.ts"), aiSrc);

    lines.splice(start, end - start + 1);
    fs.writeFileSync(file, lines.join("\n"));

    const rel = path
      .relative(ROOT, path.join(aiDir, "ai.ts"))
      .split(path.sep)
      .join("/")
      .replace(/\.ts$/, "");
    aiImports.push([meta.slug, rel]);
    terms[meta.slug] = { terms: aiObj.terms, effectTags: aiObj.effectTags };
    aiCount++;
  }
  slimCount++;
}

console.log(`slim=${slimCount} aiSplit=${aiCount}`);

const imp = aiImports
  .map(([slug, rel], i) => `import { ai as a${i} } from "./${rel}"; // ${slug}`)
  .join("\n");
const entries = aiImports.map(([slug], i) => `  "${slug}": a${i},`).join("\n");
fs.writeFileSync(
  "src/registry/ai-data.ts",
  `// AUTO-GENERATED by scripts/split-registry-ai.mjs — do not edit by hand.
// Server-only: full handwritten AI layers per slug. The client barrel must NOT
// import this file (prompts/knobs/pitfalls are the heavy part of the bundle).
import type { ResourceAILayer } from "@/types/resource";
${imp}

export const AI_DATA: Record<string, ResourceAILayer> = {
${entries}
};
`,
);

fs.writeFileSync(
  "src/registry/ai-terms.ts",
  `// AUTO-GENERATED by scripts/split-registry-ai.mjs — do not edit by hand.
// Client-safe search index: only terms + effectTags per slug (no prose).
import type { ResourceTerms } from "@/types/resource";

export const AI_TERMS: Record<string, { terms: ResourceTerms; effectTags?: string[] }> = ${JSON.stringify(terms, null, 2)};
`,
);
console.log("ai-data.ts + ai-terms.ts generated");
